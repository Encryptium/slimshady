const { chromium } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const artifacts=path.resolve(__dirname,'../../..','artifacts');fs.mkdirSync(artifacts,{recursive:true});
  const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1440,height:1000},permissions:['geolocation'],geolocation:{longitude:-84.3963748,latitude:33.7746658,accuracy:5}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error'){errors.push(m.text());console.log('Browser console:',m.text().slice(0,300));}});
  await page.goto('http://127.0.0.1:8765',{waitUntil:'networkidle'});
  await page.getByText('Where to?').waitFor();
  await page.screenshot({path:path.join(artifacts,'desktop-home.png')});
  await page.getByText('Try a Georgia Tech route').click();
  await page.getByLabel('Starting point',{exact:true}).filter({visible:true}).waitFor();
  await page.getByRole('button',{name:'Find routes'}).click({timeout:20000});
  await page.getByText('Step by step',{exact:true}).waitFor({timeout:180000});
  await page.getByRole('radio').first().scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(artifacts,'desktop-route.png')});
  console.log('Route cards:',await page.getByRole('radio').allTextContents());
  await page.getByLabel('Save route').click();
  await page.getByText('Saved on this device. No account needed.').waitFor();
  await page.getByLabel('Close dialog').click();
  await page.getByText('Behind the map',{exact:true}).click();
  await page.getByText('The data behind your route.').waitFor();
  await page.screenshot({path:path.join(artifacts,'data-evidence.png')});
  await page.getByLabel('Close dialog').click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Start walking'}).scrollIntoViewIfNeeded();
  await page.getByRole('button',{name:'Start walking'}).waitFor({state:'visible'});
  await page.screenshot({path:path.join(artifacts,'mobile-route.png')});
  await page.getByRole('button',{name:'Start walking'}).click();
  await page.getByText('On your way',{exact:true}).waitFor({timeout:180000});
  await page.getByRole('button',{name:'End route'}).click();
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('Browser smoke passed: map, search example, routing, save, evidence, mobile viewport, foreground navigation with simulated GPS.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
